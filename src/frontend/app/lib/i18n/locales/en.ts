// Same nested key shape as TranslationSchema, but every leaf is widened from
// a string literal to `string` - other locales translate the text, not
// reproduce the English literal, so pt-BR.ts is typed against this instead
// of TranslationSchema directly. A key missing from a locale (or misspelled)
// is still a compile error either way.
export type DeepStringSchema<T> = T extends string
  ? string
  : { [K in keyof T]: DeepStringSchema<T[K]> };
